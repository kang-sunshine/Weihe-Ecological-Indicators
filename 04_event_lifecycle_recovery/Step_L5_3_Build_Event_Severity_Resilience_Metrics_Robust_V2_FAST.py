def idx_to_date_string(
    indices
):

    values = []

    for x in indices:

        if (
            np.isfinite(x)
            and
            int(x) >= 0
            and
            int(x) < len(time_index)
        ):

            values.append(
                time_index[
                    int(x)
                ].strftime(
                    "%Y-%m-%d"
                )
            )

        else:

            values.append("")

    return values


