@njit(cache=True)
def nanmedian_small(a, start, end):

    buf = np.empty(
        max(end - start, 1),
        dtype=np.float32
    )

    n = 0

    for i in range(start, end):

        v = a[i]

        if np.isfinite(v):

            buf[n] = v
            n += 1

    if n < MIN_PRE_VALID:
        return np.nan

    x = np.sort(
        buf[:n]
    )

    if n % 2 == 1:

        return float(
            x[n // 2]
        )

    else:

        return float(
            (
                x[n // 2 - 1]
                +
                x[n // 2]
            )
            / 2.0
        )


@njit(cache=True)
def pre_start_idx(
    time_days,
    onset
):

    target = (
        time_days[onset]
        -
        PRE_WINDOW_DAYS
    )

    i = onset - 1

    while (
        i >= 0
        and
        time_days[i] >= target
    ):

        i -= 1

    return i + 1


@njit(cache=True)
def future_end_idx(
    time_days,
    onset,
    ndays
):

    target = (
        time_days[onset]
        +
        ndays
    )

    n = len(time_days)

    i = onset

    while (
        i < n
        and
        time_days[i] <= target
    ):

        i += 1

    return i


@njit(cache=True)
def calculate_row_events(

    event_code,

    cols,
    onsets,
    terms,

    time_days,
    phase_idx,

    tmax,
    rootsm,
    precip,

    zsync,
    zuwue,
    znirv,
    acomp,

    event_mask,
    any_mask,

    tq90,
    sq10,
    pq95
):

    """
    Arrays tmax etc are shape:
        time, x

    Threshold arrays are shape:
        phase, x

    cols/onsets/terms describe events in ONE spatial row.

    event_code:
        0 CDH
        1 HEAT
        2 HR
    """

    ne = len(cols)

    # -------------------------------------------------------------------------
    # output numeric matrix
    #
    # Column meaning defined below after kernel.
    # -------------------------------------------------------------------------

    nout = 35

    out = np.full(
        (ne, nout),
        np.nan,
        dtype=np.float64
    )


    nt = len(time_days)


    for e in range(ne):

        col = cols[e]
        onset = onsets[e]
        term = terms[e]


        # =====================================================================
        # 0 Actual duration
        # =====================================================================

        if term + 1 < nt:

            duration_actual = (
                time_days[term + 1]
                -
                time_days[onset]
            )

        else:

            duration_actual = (
                time_days[term]
                -
                time_days[onset]
                +
                8
            )


        out[e, 0] = duration_actual


        # =====================================================================
        # 1 Climate severity
        # =====================================================================

        climate_peak = -1.0
        climate_peak_idx = -1

        cumulative_severity = 0.0
        valid_severity = False

        heat_peak = -1.0
        heat_sum = 0.0
        heat_valid = False

        dry_peak = -1.0
        dry_sum = 0.0
        dry_valid = False

        rain_peak = -1.0
        rain_sum = 0.0
        rain_valid = False


        for idx in range(
            onset,
            term + 1
        ):

            # Gap-filled L5.2 phase:
            # do not add climate severity unless original event mask == true.

            if not event_mask[idx, col]:
                continue


            p = phase_idx[idx]

            tv = tmax[idx, col]
            sv = rootsm[idx, col]
            pv = precip[idx, col]

            tq = tq90[p, col]
            sq = sq10[p, col]
            pq = pq95[p, col]


            if idx + 1 < nt:

                dt = (
                    time_days[idx + 1]
                    -
                    time_days[idx]
                )

                if dt <= 0:
                    dt = 8

            else:

                dt = 8


            heat_ex = np.nan
            dry_def = np.nan
            rain_ex = np.nan


            if (
                np.isfinite(tv)
                and
                np.isfinite(tq)
            ):

                heat_ex = tv - tq

                if heat_ex < 0:
                    heat_ex = 0.0


                heat_valid = True

                if heat_ex > heat_peak:
                    heat_peak = heat_ex

                heat_sum += (
                    heat_ex
                    *
                    dt
                )


            if (
                np.isfinite(sv)
                and
                np.isfinite(sq)
            ):

                dry_def = sq - sv

                if dry_def < 0:
                    dry_def = 0.0


                dry_valid = True

                if dry_def > dry_peak:
                    dry_peak = dry_def

                dry_sum += (
                    dry_def
                    *
                    dt
                )


            if (
                np.isfinite(pv)
                and
                np.isfinite(pq)
            ):

                rain_ex = pv - pq

                if rain_ex < 0:
                    rain_ex = 0.0


                rain_valid = True

                if rain_ex > rain_peak:
                    rain_peak = rain_ex

                rain_sum += rain_ex


            intensity = np.nan


            # CDH
            if event_code == 0:

                if (
                    np.isfinite(heat_ex)
                    and
                    np.isfinite(dry_def)
                    and
                    np.isfinite(tq)
                    and
                    np.isfinite(sq)
                ):

                    htden = abs(tq)

                    if htden < 1.0:
                        htden = 1.0


                    smden = abs(sq)

                    if smden < EPS:
                        smden = EPS


                    hr = (
                        heat_ex
                        /
                        htden
                    )

                    dr = (
                        dry_def
                        /
                        smden
                    )


                    intensity = np.sqrt(
                        hr * hr
                        +
                        dr * dr
                    )


                    cumulative_severity += (
                        intensity
                        *
                        dt
                    )

                    valid_severity = True


            # HEAT
            elif event_code == 1:

                if np.isfinite(
                    heat_ex
                ):

                    intensity = (
                        heat_ex
                    )

                    cumulative_severity += (
                        heat_ex
                        *
                        dt
                    )

                    valid_severity = True


            # HR
            else:

                if np.isfinite(
                    rain_ex
                ):

                    intensity = (
                        rain_ex
                    )

                    cumulative_severity += (
                        rain_ex
                    )

                    valid_severity = True


            if np.isfinite(
                intensity
            ):

                if intensity > climate_peak:

                    climate_peak = (
                        intensity
                    )

                    climate_peak_idx = (
                        idx
                    )


        if not valid_severity:

            climate_peak = np.nan
            cumulative_severity = np.nan
            climate_peak_idx = -1


        if not heat_valid:
            heat_peak = np.nan
            heat_sum = np.nan

        if not dry_valid:
            dry_peak = np.nan
            dry_sum = np.nan

        if not rain_valid:
            rain_peak = np.nan
            rain_sum = np.nan


        out[e, 1] = climate_peak
        out[e, 2] = climate_peak_idx
        out[e, 3] = cumulative_severity

        out[e, 4] = heat_peak
        out[e, 5] = heat_sum

        out[e, 6] = dry_peak
        out[e, 7] = dry_sum

        out[e, 8] = rain_peak
        out[e, 9] = rain_sum


        # =====================================================================
        # 2 Pre-event medians
        # =====================================================================

        p0 = pre_start_idx(
            time_days,
            onset
        )


        zsync_pre = nanmedian_small(
            zsync[:, col],
            p0,
            onset
        )

        zuwue_pre = nanmedian_small(
            zuwue[:, col],
            p0,
            onset
        )

        znirv_pre = nanmedian_small(
            znirv[:, col],
            p0,
            onset
        )

        acomp_pre = nanmedian_small(
            acomp[:, col],
            p0,
            onset
        )


        out[e, 10] = zsync_pre
        out[e, 11] = zuwue_pre
        out[e, 12] = znirv_pre
        out[e, 13] = acomp_pre


        # =====================================================================
        # 3 Peak ecosystem responses
        # =====================================================================

        pend = future_end_idx(
            time_days,
            onset,
            PEAK_SEARCH_DAYS
        )


        # -------------------------------------------------
        # ZSync minimum
        # -------------------------------------------------

        zsync_min = np.nan
        zsync_idx = -1

        for idx in range(
            onset,
            pend
        ):

            v = zsync[
                idx,
                col
            ]

            if np.isfinite(v):

                if (
                    zsync_idx < 0
                    or
                    v < zsync_min
                ):

                    zsync_min = v
                    zsync_idx = idx


        if (
            zsync_idx >= 0
            and
            np.isfinite(
                zsync_pre
            )
        ):

            out[e, 14] = zsync_min

            out[e, 15] = (
                zsync_pre
                -
                zsync_min
            )

            out[e, 16] = zsync_idx

            out[e, 17] = (
                time_days[zsync_idx]
                -
                time_days[onset]
            )


        # -------------------------------------------------
        # ZuWUE minimum
        # -------------------------------------------------

        zuwue_min = np.nan
        zuwue_idx = -1

        for idx in range(
            onset,
            pend
        ):

            v = zuwue[
                idx,
                col
            ]

            if np.isfinite(v):

                if (
                    zuwue_idx < 0
                    or
                    v < zuwue_min
                ):

                    zuwue_min = v
                    zuwue_idx = idx


        if (
            zuwue_idx >= 0
            and
            np.isfinite(
                zuwue_pre
            )
        ):

            out[e, 18] = zuwue_min

            out[e, 19] = (
                zuwue_pre
                -
                zuwue_min
            )

            out[e, 20] = zuwue_idx

            out[e, 21] = (
                time_days[zuwue_idx]
                -
                time_days[onset]
            )


        # -------------------------------------------------
        # ZNIRv minimum
        # -------------------------------------------------

        znirv_min = np.nan
        znirv_idx = -1

        for idx in range(
            onset,
            pend
        ):

            v = znirv[
                idx,
                col
            ]

            if np.isfinite(v):

                if (
                    znirv_idx < 0
                    or
                    v < znirv_min
                ):

                    znirv_min = v
                    znirv_idx = idx


        if (
            znirv_idx >= 0
            and
            np.isfinite(
                znirv_pre
            )
        ):

            out[e, 22] = znirv_min

            out[e, 23] = (
                znirv_pre
                -
                znirv_min
            )

            out[e, 24] = znirv_idx

            out[e, 25] = (
                time_days[znirv_idx]
                -
                time_days[onset]
            )


        # -------------------------------------------------
        # Acomp maximum
        # -------------------------------------------------

        acomp_max = np.nan
        acomp_idx = -1

        for idx in range(
            onset,
            pend
        ):

            v = acomp[
                idx,
                col
            ]

            if np.isfinite(v):

                if (
                    acomp_idx < 0
                    or
                    v > acomp_max
                ):

                    acomp_max = v
                    acomp_idx = idx


        if (
            acomp_idx >= 0
            and
            np.isfinite(
                acomp_pre
            )
        ):

            out[e, 26] = acomp_max

            out[e, 27] = (
                acomp_max
                -
                acomp_pre
            )

            out[e, 28] = acomp_idx

            out[e, 29] = (
                time_days[acomp_idx]
                -
                time_days[onset]
            )


        # =====================================================================
        # 4 Next-event censor
        # =====================================================================

        rend = future_end_idx(
            time_days,
            onset,
            MAX_RECOVERY_DAYS
        )


        next_event_idx = -1


        for idx in range(
            term + 1,
            rend
        ):

            if any_mask[
                idx,
                col
            ]:

                next_event_idx = idx
                break


        out[e, 30] = (
            next_event_idx
        )


        # =====================================================================
        # 5 Recovery + legacy
        # =====================================================================

        if (
            acomp_idx >= 0
            and
            np.isfinite(
                acomp_pre
            )
        ):

            censor_end = rend

            has_event_censor = False


            if (
                next_event_idx >= 0
                and
                next_event_idx
                <
                censor_end
            ):

                censor_end = (
                    next_event_idx
                )

                has_event_censor = True


            recovery_idx = -1

            consecutive = 0


            for idx in range(
                acomp_idx + 1,
                censor_end
            ):

                v = acomp[
                    idx,
                    col
                ]


                if not np.isfinite(v):

                    consecutive = 0
                    continue


                if v <= acomp_pre:

                    consecutive += 1

                else:

                    consecutive = 0


                if (
                    consecutive
                    >=
                    RECOVERY_CONSECUTIVE
                ):

                    recovery_idx = (
                        idx
                        -
                        RECOVERY_CONSECUTIVE
                        +
                        1
                    )

                    break


            # recovery index
            out[e, 31] = recovery_idx


            if recovery_idx >= 0:

                out[e, 32] = (
                    time_days[
                        recovery_idx
                    ]
                    -
                    time_days[
                        onset
                    ]
                )

                # not censored if recovery occurred
                out[e, 33] = 0.0

                legacy_stop = (
                    recovery_idx
                )

            else:

                if has_event_censor:
                    out[e, 33] = 1.0
                else:
                    out[e, 33] = 0.0

                legacy_stop = (
                    censor_end
                )


            # -------------------------------------------------------------
            # Acomp legacy
            # -------------------------------------------------------------

            legacy = 0.0
            legacy_valid = False


            for idx in range(
                term + 1,
                legacy_stop
            ):

                v = acomp[
                    idx,
                    col
                ]

                if not np.isfinite(v):
                    continue


                if idx + 1 < nt:

                    dt = (
                        time_days[
                            idx + 1
                        ]
                        -
                        time_days[
                            idx
                        ]
                    )

                else:

                    dt = 8


                if dt <= 0:
                    continue


                excess = (
                    v
                    -
                    acomp_pre
                )

                if excess < 0:
                    excess = 0.0


                legacy += (
                    excess
                    *
                    dt
                )

                legacy_valid = True


            if legacy_valid:

                out[e, 34] = (
                    legacy
                )


    return out


